/** Icon for a social menu item, by its label ("LinkedIn", "Bluesky", …). */
export const socialIcon = (label: string): string | undefined => ICONS[label.toLowerCase().replace(/[^a-z]/g, "")];

const NETWORKS: [RegExp, string, string][] = [
	[/(^|\.)linkedin\.com$/, "linkedin", "LinkedIn"],
	[/(^|\.)github\.com$/, "github", "GitHub"],
	[/(^|\.)(x|twitter)\.com$/, "x", "X"],
	[/(^|\.)bsky\.app$/, "bluesky", "Bluesky"],
	[/(^|\.)youtube\.com$/, "youtube", "YouTube"],
];

/** A profile link (one per line in a person's "Profile links") with its network name and icon. */
export function profileLink(
	url: string,
): { url: string; network: string; icon: string; viewBox: string } | undefined {
	let parsed: URL;
	try {
		parsed = new URL(url.trim());
	} catch {
		return undefined;
	}
	if (!/^https?:$/.test(parsed.protocol)) return undefined;
	const host = parsed.hostname.replace(/^www\./, "");
	const known = NETWORKS.find(([pattern]) => pattern.test(host));
	const viewBox = "0 0 24 24";
	if (known) return { url: parsed.href, network: known[2], icon: ICONS[known[1]], viewBox };
	// Mastodon servers have many names, but profiles all look like /@name.
	if (parsed.pathname.startsWith("/@")) return { url: parsed.href, network: "Mastodon", icon: ICONS.mastodon, viewBox };
	return { url: parsed.href, network: "Website", icon: GLOBE.path, viewBox: GLOBE.viewBox };
}

/** The profile links of a multi-line field. */
export const profileLinks = (text: string | null | undefined) =>
	(text ?? "")
		.split("\n")
		.map(profileLink)
		.filter((link) => link !== undefined);
